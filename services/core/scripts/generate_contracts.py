"""Generate the contracts in packages/contracts from the code (decision 0006, phase 4).

  PYTHONPATH=. python scripts/generate_contracts.py          write the files
  PYTHONPATH=. python scripts/generate_contracts.py --check  exit 1 if a file is out of date

Writes:
  packages/contracts/schemas/pack-manifest.schema.json   JSON Schema of the pack manifest the server accepts
  packages/contracts/openapi/nortpole-api.json           OpenAPI description of NortPole's own routes

The schema covers structure (fields, types, lengths, enums); the server also runs cross-field checks the schema cannot
express, such as unique template ids and guides that exist. The API description covers only routes whose handlers live
in NortPole's domains and top-level modules, not the inherited platform's routes.
"""

import json
import sys
from pathlib import Path

CORE = Path(__file__).resolve().parents[1]
REPO = CORE.parents[1]
CONTRACTS = REPO / "packages" / "contracts"
SCHEMA_PATH = CONTRACTS / "schemas" / "pack-manifest.schema.json"
OPENAPI_PATH = CONTRACTS / "openapi" / "nortpole-api.json"
OWN_MODULE_PREFIXES = (
    "nortpole.governance.",
    "nortpole.work.",
    "nortpole.knowledge.",
    "nortpole.insight.",
    "nortpole.user_preferences.",
)


def _dump(data: dict) -> str:
    return json.dumps(data, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def pack_manifest_schema() -> str:
    from nortpole.work.packs.manifest import Manifest

    schema = Manifest.model_json_schema()
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["$id"] = "https://evolvxsi.local/contracts/pack-manifest.schema.json"
    return _dump(schema)


def evolvxsi_openapi() -> str:
    from fastapi.openapi.utils import get_openapi
    from fastapi.routing import APIRoute

    import nortpole.main as main

    app = main.get_application()
    routes = [
        r
        for r in app.routes
        if isinstance(r, APIRoute) and r.endpoint.__module__.startswith(OWN_MODULE_PREFIXES)
    ]
    spec = get_openapi(
        title="NortPole API (NortPole routes)",
        version="1",
        description="Routes implemented by NortPole's own modules. Generated by services/core/scripts/generate_contracts.py.",
        routes=sorted(routes, key=lambda r: (r.path, sorted(r.methods))),
    )
    return _dump(spec)


def outputs() -> dict[Path, str]:
    return {SCHEMA_PATH: pack_manifest_schema(), OPENAPI_PATH: evolvxsi_openapi()}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, text in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if check:
            stale.append(path.relative_to(REPO).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO)}")
    if stale:
        print("Out of date; run scripts/generate_contracts.py: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
