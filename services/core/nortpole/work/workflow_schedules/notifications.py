"""Create private Inbox updates for scheduled workflow results."""

from sqlalchemy import select
from sqlalchemy.orm import Session

from nortpole.configs.constants import NotificationType
from nortpole.db.notification import create_notification
from nortpole.utils.logger import setup_logger
from nortpole.work.tasks.models import NortPoleTask
from nortpole.work.tasks.states import TaskState
from nortpole.work.workflow_schedules.models import (
    NortPoleWorkflowRun,
    NortPoleWorkflowSchedule,
)

logger = setup_logger()


def notify_scheduled_run(
    db: Session, schedule: NortPoleWorkflowSchedule, run: NortPoleWorkflowRun
) -> None:
    data = {
        "schedule_id": str(schedule.id),
        "run_id": str(run.id),
        "link": f"/app/workflows/scheduled?schedule={schedule.id}&run={run.id}",
    }
    reason = run.reason
    if run.outcome == "plan_ready" and schedule.notify_plan_ready and run.task_id:
        kind = NotificationType.WORKFLOW_PLAN_READY
        title = f'Plan ready for "{schedule.name}"'
        reason = "Review the plan before work begins."
        data["task_id"] = str(run.task_id)
        data["link"] = f"/app/workflows/drafts?task={run.task_id}"
    elif run.outcome == "needs_review" and schedule.notify_needs_review:
        kind = NotificationType.WORKFLOW_RUN_NEEDS_REVIEW
        title = f'"{schedule.name}" needs review'
        reason = "Open the result to see what needs your attention."
    elif run.outcome == "review_complete" and schedule.notify_run_complete:
        kind = NotificationType.WORKFLOW_RUN_COMPLETE
        title = f'"{schedule.name}" finished'
        reason = "The review is ready to open."
    elif run.outcome in {"plan_failed", "skipped", "drive_skipped", "interrupted"} and schedule.notify_run_failed:
        kind = NotificationType.WORKFLOW_RUN_FAILED
        title = f'"{schedule.name}" could not finish'
        reason = reason or "Open the run history for details."
    else:
        return

    if run.chat_session_id:
        data["chat_session_id"] = str(run.chat_session_id)
        data["link"] = f"/app?chatId={run.chat_session_id}"
    _send(db, schedule, kind, title, reason, data)


def notify_scheduled_task_result(db: Session, task: NortPoleTask) -> None:
    """Notify after the owner runs a plan generated by a schedule."""
    if task.schedule_id is None:
        return
    try:
        schedule = db.get(NortPoleWorkflowSchedule, task.schedule_id)
        if schedule is None or schedule.owner_id != task.owner_id:
            return
        if task.state == TaskState.RUN_FAILED.value and schedule.notify_run_failed:
            kind = NotificationType.WORKFLOW_RUN_FAILED
            title = f'"{schedule.name}" could not finish'
            reason = task.run_error or "Open the draft for details."
        elif task.state == TaskState.DRAFT_READY.value and schedule.notify_run_complete:
            kind = NotificationType.WORKFLOW_RUN_COMPLETE
            title = f'"{schedule.name}" finished'
            reason = "The cited draft is ready for review."
        else:
            return
        run_id = db.scalar(
            select(NortPoleWorkflowRun.id)
            .where(NortPoleWorkflowRun.schedule_id == schedule.id, NortPoleWorkflowRun.task_id == task.id)
            .order_by(NortPoleWorkflowRun.fired_at.desc())
            .limit(1)
        )
        if run_id is not None:
            _send(db, schedule, kind, title, reason, {
                "schedule_id": str(schedule.id), "run_id": str(run_id),
                "task_id": str(task.id), "task_version": task.version,
                "link": f"/app/workflows/drafts?task={task.id}",
            })
    except Exception:
        db.rollback()
        logger.exception("Could not look up scheduled task result %s", task.id)


def _send(
    db: Session, schedule: NortPoleWorkflowSchedule, kind: NotificationType,
    title: str, reason: str | None, data: dict[str, str | int],
) -> None:
    try:
        create_notification(
            user_id=schedule.owner_id, notif_type=kind, db_session=db,
            title=title, description=reason, additional_data=data, refresh_existing=False,
        )
    except Exception:
        db.rollback()
        logger.exception("Could not notify the owner of workflow run %s", data["run_id"])
